test('video upload pauses, survives reload, resumes and explicitly discards',async({page})=>{
 test.setTimeout(60000)
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/#asr')
 await page.getByRole('tab',{name:'新建视频转写',exact:true}).click()
 await page.locator('input[type=file]').setInputFiles(videoPath)
 let release:()=>void=()=>undefined
 const held=new Promise<void>(resolve=>{release=resolve})
 const handler=async(route:import('@playwright/test').Route)=>{if(route.request().method()==='PATCH'){await held;try{await route.abort()}catch(error){if(!(error instanceof Error)||!error.message.includes('already handled'))throw error}}else await route.continue()}
 await page.route('**/api/v1/asr/video-uploads/*',handler)
 const request=page.waitForRequest(request=>request.method()==='PATCH'&&request.url().includes('/video-uploads/'))
 await page.getByRole('button',{name:'开始转写',exact:true}).click();await request
 await page.getByRole('button',{name:'暂停上传',exact:true}).click()
 release();await page.unroute('**/api/v1/asr/video-uploads/*',handler)
 await expect(page.locator('.video-resume')).toBeVisible()
 await page.reload();await page.getByRole('tab',{name:'新建视频转写',exact:true}).click()
 await expect(page.locator('.video-resume')).toContainText('lecture.webm')
 await page.locator('input[type=file]').setInputFiles(videoPath)
 await page.getByRole('button',{name:'开始转写',exact:true}).click()
 await expect(page.getByRole('button',{name:'查看本次任务'})).toBeVisible({timeout:30000})
 expect(await page.evaluate(()=>sessionStorage.getItem('audio-intel:video-upload:v1'))).toBeNull()
 // A separate idle session is cleaned immediately through the accessible dialog.
 const upload=await page.request.post('/api/v1/asr/video-uploads',{headers:{'Idempotency-Key':`discard-${Date.now()}`},data:{name:'discard.mp4',size_bytes:20}})
 expect(upload.ok()).toBe(true)
 const item=await upload.json()
 await page.evaluate(item=>sessionStorage.setItem('audio-intel:video-upload:v1',JSON.stringify({id:item.id,name:item.name,size:item.size_bytes,createKey:'discard-key',jobKey:'discard-job',params:{}})),item)
 await page.reload();await page.getByRole('tab',{name:'新建视频转写',exact:true}).click()
 await page.getByRole('button',{name:'清理未完成上传',exact:true}).click()
 await page.getByRole('dialog').getByRole('button',{name:'清理未完成上传',exact:true}).click()
 await expect(page.locator('.video-resume')).toHaveCount(0)
 expect((await page.request.get(`/api/v1/asr/video-uploads/${item.id}`)).status()).toBe(404)
 expect(errors).toEqual([])
})
