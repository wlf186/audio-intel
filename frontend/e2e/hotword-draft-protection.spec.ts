import {test,expect} from './fixtures'
import {uxFixture} from './ux-fixtures'

for(const width of [1280,1920,390])test(`hotword switching and clearing protect an unsaved draft ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:900})
 const {errors}=await uxFixture(page)
 const lists=[{id:'a',name:'项目甲',terms:['Atlas'],kind:'custom'},{id:'b',name:'项目乙',terms:['Qwen'],kind:'custom'},{id:'system',name:'系统名单',terms:['Alice'],kind:'system'}].map(item=>({...item,term_count:1,created_at:'2026-10-28T00:00:00Z',updated_at:'2026-10-28T00:00:00Z'}))
 await page.route('**/api/v1/asr/hotword-lists',route=>route.fulfill({json:{items:lists,count:lists.length}}))
 await page.goto('/#library/hotwords')
 const name=page.getByLabel('场景名称'),terms=page.locator('.hotword-editor textarea')
 await page.getByRole('button',{name:'编辑 项目甲',exact:true}).click()
 await terms.fill('Atlas\n未保存的术语')
 await page.getByRole('button',{name:'编辑 项目乙',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'放弃未保存的词表编辑？'})
 await expect(dialog).toBeVisible()
 await dialog.getByRole('button',{name:'取消',exact:true}).click()
 await expect(name).toHaveValue('项目甲')
 await expect(terms).toHaveValue('Atlas\n未保存的术语')
 await page.reload()
 await expect(terms).toHaveValue('Atlas\n未保存的术语')
 await page.getByRole('button',{name:'查看 系统名单',exact:true}).click()
 await expect(dialog).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('protected-draft.png'),fullPage:true})
 await dialog.getByRole('button',{name:'放弃并继续',exact:true}).click()
 await expect(terms).toHaveValue('Alice')
 await expect(terms).toBeDisabled()
 await expect.poll(()=>page.evaluate(()=>sessionStorage.getItem('audio-intel:hotword-draft:v1'))).toBeNull()
 await page.getByRole('button',{name:'编辑 项目乙',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await page.getByRole('button',{name:'取消并清空',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await name.fill('新词表草稿')
 await terms.fill('一个术语')
 await page.getByRole('button',{name:'取消并清空',exact:true}).click()
 await expect(dialog).toBeVisible()
 await dialog.getByRole('button',{name:'取消',exact:true}).click()
 await expect(name).toHaveValue('新词表草稿')
 await page.getByRole('button',{name:'取消并清空',exact:true}).click()
 await dialog.getByRole('button',{name:'放弃并继续',exact:true}).click()
 await expect(name).toHaveValue('')
 await expect(terms).toHaveValue('')
 expect(errors).toEqual([])
})
